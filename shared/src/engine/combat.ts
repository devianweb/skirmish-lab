import { DiceSpec, DiceResult } from '../types';
import { getTraitValue, hasTrait, sumTraitValue } from '../rules/traits';

/**
 * Quality/Defense d6 combat, trauma, and morale resolution (first principles).
 *
 * Core Axioms:
 *   - Natural 1 always fails; Natural 6 always succeeds.
 *   - To-Hit:  roll + hitMod >= baseQuality -> hit
 *   - Defense: roll + coverBonus + shieldBonus - ap >= defense -> hit blocked
 *   - Trauma:  1d6 + accumulatedTokens (natural 1 always Shaken; 1-5 Shaken, 6+ Knocked Out)
 *   - Morale:  1d6 + moraleMod >= effectiveQuality
 *
 * Dice are always rolled by the signaling server (never client-side).
 */

export interface AttackRolls {
  toHit: number[];
  defense: number[];
  regeneration?: number[];
  trauma?: number[];
}

export interface TraumaOutcome {
  roll: number;
  tokens: number;
  fearBonus: number;
  total: number;
  outcome: 'shaken' | 'knocked-out';
}

export interface MoraleTestInput {
  quality: number;
  roll: number;
  specialRules?: string[];
  alreadyShaken?: boolean;
  /** Optional nearby Hero quality within 12". */
  heroQuality?: number;
  /** Optional 1d6 roll for Fearless (Fearless 4+ pass on failure). */
  fearlessRoll?: number;
  /** Optional dice rolls for Iron Will (No Retreat self-wounds on 1-3). */
  ironWillRolls?: number[];
}

export interface MoraleTestOutcome {
  roll: number;
  modifier: number;
  effectiveQuality: number;
  passed: boolean;
  fearlessSaved?: boolean;
  ironWillUsed?: boolean;
  ironWillWounds?: number;
  outcome: 'passed' | 'shaken' | 'routed';
}

export interface CombatOutcome {
  attackCount: number;
  toHitRolls: number[];
  /** hitRolls[i] is true when toHitRolls[i] scored a hit. */
  hitRolls: boolean[];
  /** Bonus hits generated by natural 6s (relentless, furious, surge). */
  bonusHits: number;
  /** Total hits after bonus hits and blast(X) multiplication. */
  hitCount: number;
  defenseRolls: number[];
  /** Re-rolled defense dice when defender rolled a natural 6 against a bane (Bane) attack. */
  rerolledDefenseRolls: number[];
  /** blockedRolls[i] is true when the i-th hit was blocked. */
  blockedRolls: boolean[];
  blockedCount: number;
  /** Wounds prevented by Regeneration (Regeneration 5+). */
  regenerationRolls: number[];
  regenerationSavedCount: number;
  wounds: number;
  effectiveQuality: number;
  effectiveDefense: number;
  coverApplied: boolean;
  apApplied: number;
  baseQuality: number;
  hitModifiers: string[];
  baseDefense: number;
  defenseModifiers: string[];
}

export interface CombatStats {
  quality: number;
  /** Unit special rules (marksman, furious, surge, rupture, etc.). */
  specialRules?: string[];
  /** Weapon special rules (ap(X), blast(X), deadly(X), rending, reliable, etc.). */
  weaponRules?: string[];
  /** True when this attack is a melee strike. */
  isMelee?: boolean;
  /** True when the attacker charged this activation. */
  isCharging?: boolean;
  /** True when the attacker has already moved this activation. */
  hasMoved?: boolean;
  /** True when the attacker is fatigued or shaken in melee — only hits on natural 6. */
  isFatigued?: boolean;
  /** Distance to target in board units (inches). */
  distance?: number;
}

export interface DefenseStats {
  defense: number;
  inCover?: boolean;
  /** Defender special rules (stealth, riot-shield, regeneration, entrenched, etc.). */
  specialRules?: string[];
  /** Number of alive models in the defending unit (caps blast(X), default 1). */
  modelCount?: number;
  /** Whether the defending unit has moved this round (used by entrenched). */
  hasMoved?: boolean;
}

export interface AttackDiceOptions {
  attackerRules?: string[];
  weaponRules?: string[];
  defenderRules?: string[];
  defenderModelCount?: number;
  isMelee?: boolean;
  isCharging?: boolean;
  isFatigued?: boolean;
  distance?: number;
  includeTrauma?: boolean;
}

/**
 * Dice specs for one attack. When called without `options`, returns `count`
 * to-hit dice and `count` defense dice. When `options` are provided, scales
 * defense dice for blast/bonus-hit/bane worst-case and appends regeneration/trauma
 * dice when applicable.
 */
export function getAttackDiceSpecs(
  attackCount: number,
  options?: AttackDiceOptions
): DiceSpec[] {
  if (!options) {
    return [
      { count: attackCount, sides: 6, purpose: 'to-hit' },
      { count: attackCount, sides: 6, purpose: 'defense' },
    ];
  }

  const allAttackerRules = [
    ...(options.attackerRules ?? []),
    ...(options.weaponRules ?? []),
  ];
  const defenderRules = options.defenderRules ?? [];
  const isMelee = !!options.isMelee;
  const isCharging = !!options.isCharging;
  const distance = options.distance ?? (isMelee ? 1 : 12);

  const bonusPerSix =
    (hasTrait(allAttackerRules, 'surge') ? 1 : 0) +
    (!isMelee && distance > 9 && hasTrait(allAttackerRules, 'relentless') ? 1 : 0) +
    (isMelee && isCharging && hasTrait(allAttackerRules, 'furious') ? 1 : 0);

  const blastVal = getTraitValue(allAttackerRules, 'blast');
  const modelCap = Math.max(1, options.defenderModelCount ?? 1);
  const blastMultiplier = blastVal !== undefined ? Math.min(blastVal, modelCap) : 1;

  const maxHits = attackCount * (1 + bonusPerSix) * blastMultiplier;
  const baneMultiplier = hasTrait(allAttackerRules, 'bane') ? 2 : 1;
  const defenseDiceCount = Math.max(attackCount, maxHits * baneMultiplier);

  const specs: DiceSpec[] = [
    { count: attackCount, sides: 6, purpose: 'to-hit' },
    { count: defenseDiceCount, sides: 6, purpose: 'defense' },
  ];

  const ignoresRegeneration =
    hasTrait(allAttackerRules, 'bane') ||
    hasTrait(allAttackerRules, 'unstoppable') ||
    hasTrait(allAttackerRules, 'rending');

  if (hasTrait(defenderRules, 'regeneration') && !ignoresRegeneration) {
    const deadlyMult = getTraitValue(allAttackerRules, 'deadly') ?? 1;
    specs.push({ count: maxHits * deadlyMult, sides: 6, purpose: 'regeneration' });
  }

  if (options.includeTrauma) {
    specs.push({ count: 1, sides: 6, purpose: 'trauma' });
  }

  return specs;
}

export interface CombatModifierBreakdown {
  baseQuality: number;
  hitModifiers: string[];
  effectiveQuality: number;
  baseDefense: number;
  defenseModifiers: string[];
  effectiveDefense: number;
  baseAp: number;
  coverApplied: boolean;
}

/**
 * Compute the explicit breakdown of Quality, Hit Modifiers, Defense, and Defense Modifiers.
 */
export function computeCombatModifiers(
  attacker: CombatStats,
  defender: DefenseStats,
  weaponRules: string[] = []
): CombatModifierBreakdown {
  const allAttackerRules = [
    ...(attacker.specialRules ?? []),
    ...(attacker.weaponRules ?? weaponRules),
  ];
  const defenderRules = defender.specialRules ?? [];
  const isMelee = !!attacker.isMelee;
  const isCharging = !!attacker.isCharging;
  const distance = attacker.distance ?? (isMelee ? 1 : 12);

  const baseQuality = hasTrait(allAttackerRules, 'reliable') ? 2 : attacker.quality;
  let hitMod = 0;
  const hitModifiers: string[] = [];

  if (hasTrait(allAttackerRules, 'reliable')) {
    hitModifiers.push('Reliable (Q2)');
  }
  if (!isMelee) {
    if (hasTrait(allAttackerRules, 'marksman')) {
      hitMod += 1;
      hitModifiers.push('+1 Marksman');
    }
    if (hasTrait(defenderRules, 'stealth') && distance > 9) {
      hitMod -= 1;
      hitModifiers.push('-1 Stealth (>9")');
    }
    if (hasTrait(defenderRules, 'entrenched') && !defender.hasMoved && distance > 9) {
      hitMod -= 1;
      hitModifiers.push('-1 Entrenched (>9")');
    }
    if (hasTrait(allAttackerRules, 'indirect') && attacker.hasMoved) {
      hitMod -= 1;
      hitModifiers.push('-1 Indirect (moved)');
    }
  } else {
    if (hasTrait(allAttackerRules, 'thrust') && isCharging) {
      hitMod += 1;
      hitModifiers.push('+1 Thrust (charge)');
    }
  }

  if (hasTrait(allAttackerRules, 'unstoppable') && hitMod < 0) {
    hitModifiers.push('Unstoppable (negates penalty)');
    hitMod = 0;
  }

  const isFatiguedMelee = isMelee && !!attacker.isFatigued;
  if (isFatiguedMelee) {
    hitModifiers.push('Fatigued (need 6)');
  }
  const effectiveQuality = isFatiguedMelee
    ? 6
    : Math.max(2, Math.min(6, baseQuality - hitMod));

  const baseAp =
    sumTraitValue(allAttackerRules, 'ap') +
    (isMelee && isCharging && hasTrait(allAttackerRules, 'thrust') ? 1 : 0);

  const blastVal = getTraitValue(allAttackerRules, 'blast');
  const hasBlast = blastVal !== undefined;
  const coverApplied = !isMelee && !!defender.inCover && !hasBlast;
  const coverBonus = coverApplied ? 1 : 0;
  const defenseModifiers: string[] = [];
  if (coverApplied) {
    defenseModifiers.push('+1 Cover');
  }
  const shieldBonus = hasTrait(defenderRules, 'riot-shield') ? 1 : 0;
  if (shieldBonus > 0) {
    defenseModifiers.push('+1 Riot Shield');
  }
  if (baseAp > 0) {
    defenseModifiers.push(`-${baseAp} AP(${baseAp})`);
  }

  const effectiveDefense = Math.max(
    2,
    Math.min(6, defender.defense - coverBonus - shieldBonus + baseAp)
  );

  return {
    baseQuality,
    hitModifiers,
    effectiveQuality,
    baseDefense: defender.defense,
    defenseModifiers,
    effectiveDefense,
    baseAp,
    coverApplied,
  };
}

/**
 * Resolve one attack deterministically from pre-rolled server dice.
 */
export function resolveAttack(
  attacker: CombatStats,
  defender: DefenseStats,
  attackCount: number,
  rolls: AttackRolls
): CombatOutcome {
  if (rolls.toHit.length < attackCount || rolls.defense.length < attackCount) {
    throw new Error(
      `Incomplete dice results: need ${attackCount} to-hit and ${attackCount} defense rolls`
    );
  }

  const allAttackerRules = [
    ...(attacker.specialRules ?? []),
    ...(attacker.weaponRules ?? []),
  ];
  const defenderRules = defender.specialRules ?? [];
  const isMelee = !!attacker.isMelee;
  const isCharging = !!attacker.isCharging;
  const distance = attacker.distance ?? (isMelee ? 1 : 12);

  const modifiers = computeCombatModifiers(attacker, defender);
  const {
    baseQuality,
    hitModifiers,
    effectiveQuality,
    baseDefense,
    defenseModifiers,
    effectiveDefense,
    baseAp,
    coverApplied,
  } = modifiers;

  const isFatiguedMelee = isMelee && !!attacker.isFatigued;
  const hitMod = baseQuality - effectiveQuality;

  const toHitRolls = rolls.toHit.slice(0, attackCount);
  const hitRolls = toHitRolls.map((roll) => {
    if (roll <= 1) return false; // Natural 1 always misses
    if (roll >= 6) return true;  // Natural 6 always hits
    if (isFatiguedMelee) return false;
    return roll + hitMod >= baseQuality;
  });

  // 2. Hit Expansion (Bonus hits on 6s, Blast(X), per-hit AP & Regeneration bypass)
  const baseIgnoresRegeneration =
    hasTrait(allAttackerRules, 'bane') ||
    hasTrait(allAttackerRules, 'unstoppable') ||
    hasTrait(allAttackerRules, 'rending');

  const bonusPerSix =
    (hasTrait(allAttackerRules, 'surge') ? 1 : 0) +
    (!isMelee && distance > 9 && hasTrait(allAttackerRules, 'relentless') ? 1 : 0) +
    (isMelee && isCharging && hasTrait(allAttackerRules, 'furious') ? 1 : 0);

  const blastVal = getTraitValue(allAttackerRules, 'blast');
  const modelCap = Math.max(1, defender.modelCount ?? 1);
  const blastMultiplier = blastVal !== undefined ? Math.min(blastVal, modelCap) : 1;

  const expandedHits: Array<{ ap: number; ignoresRegeneration: boolean }> = [];
  let bonusHits = 0;

  for (let i = 0; i < attackCount; i++) {
    if (!hitRolls[i]) continue;
    const isSix = toHitRolls[i] >= 6;
    let hitAp = baseAp;
    if (isSix && hasTrait(allAttackerRules, 'rending')) {
      hitAp = Math.max(hitAp, 4);
    }
    if (isSix && hasTrait(allAttackerRules, 'rupture')) {
      hitAp += 2;
    }

    const extraFromSix = isSix ? bonusPerSix : 0;
    bonusHits += extraFromSix;
    const copies = (1 + extraFromSix) * blastMultiplier;
    for (let c = 0; c < copies; c++) {
      expandedHits.push({ ap: hitAp, ignoresRegeneration: baseIgnoresRegeneration });
    }
  }

  const hitCount = expandedHits.length;

  // 3. Defense Rolls (Cover +1, Riot Shield +1, AP -AP, Bane re-rolls 6s)
  const isBane = hasTrait(allAttackerRules, 'bane');
  const coverBonus = coverApplied ? 1 : 0;
  const shieldBonus = hasTrait(defender.specialRules ?? [], 'riot-shield') ? 1 : 0;

  const usedDefenseRolls: number[] = [];
  const rerolledDefenseRolls: number[] = [];
  const blockedRolls: boolean[] = [];
  const unblockedHits: Array<{ ap: number; ignoresRegeneration: boolean }> = [];

  let defCursor = 0;
  for (const hit of expandedHits) {
    const rawRoll =
      defCursor < rolls.defense.length
        ? rolls.defense[defCursor++]
        : rolls.defense[rolls.defense.length - 1];

    let finalDefRoll = rawRoll;
    if (rawRoll >= 6 && isBane && defCursor < rolls.defense.length) {
      rerolledDefenseRolls.push(rawRoll);
      finalDefRoll = rolls.defense[defCursor++];
    }
    usedDefenseRolls.push(finalDefRoll);

    let blocked: boolean;
    if (finalDefRoll <= 1) {
      blocked = false; // Natural 1 always fails
    } else if (finalDefRoll >= 6) {
      blocked = true;  // Natural 6 always blocks
    } else {
      blocked = finalDefRoll + coverBonus + shieldBonus - hit.ap >= defender.defense;
    }

    blockedRolls.push(blocked);
    if (!blocked) {
      unblockedHits.push(hit);
    }
  }

  const blockedCount = blockedRolls.filter(Boolean).length;

  // 4. Wound Multipliers (Deadly(X)) & Regeneration (Regeneration 5+)
  const deadlyMult = getTraitValue(allAttackerRules, 'deadly') ?? 1;
  const hasRegeneration = hasTrait(defenderRules, 'regeneration');
  const regenerationRolls: number[] = [];
  let regenerationSavedCount = 0;
  let regenerationCursor = 0;
  let wounds = 0;

  for (const hit of unblockedHits) {
    for (let w = 0; w < deadlyMult; w++) {
      if (hasRegeneration && !hit.ignoresRegeneration && rolls.regeneration && regenerationCursor < rolls.regeneration.length) {
        const wRoll = rolls.regeneration[regenerationCursor++];
        regenerationRolls.push(wRoll);
        if (wRoll >= 5) {
          regenerationSavedCount += 1;
          continue;
        }
      }
      wounds += 1;
    }
  }

  return {
    attackCount,
    toHitRolls,
    hitRolls,
    bonusHits,
    hitCount,
    defenseRolls: usedDefenseRolls,
    rerolledDefenseRolls,
    blockedRolls,
    blockedCount,
    regenerationRolls,
    regenerationSavedCount,
    wounds,
    effectiveQuality,
    effectiveDefense,
    coverApplied,
    apApplied: baseAp,
    baseQuality,
    hitModifiers,
    baseDefense,
    defenseModifiers,
  };
}

/**
 * Resolve a Trauma Table roll (1d6 + accumulated trauma tokens + fear bonus):
 *   - Unmodified roll of 1 always results in 'shaken' (never Knocked Out).
 *   - Score 1-5: 'shaken' (Suppressed / Shaken).
 *   - Score 6+:  'knocked-out' (Eliminated / Destroyed).
 */
export function resolveTraumaRoll(
  roll: number,
  accumulatedTokens: number,
  fearBonus: number = 0,
  koThreshold: number = 6
): TraumaOutcome {
  const tokens = Math.max(1, accumulatedTokens);
  if (roll <= 1) {
    return {
      roll,
      tokens,
      fearBonus,
      total: 1,
      outcome: 'shaken',
    };
  }
  const total = roll + tokens + Math.max(0, fearBonus);
  return {
    roll,
    tokens,
    fearBonus,
    total,
    outcome: total >= koThreshold ? 'knocked-out' : 'shaken',
  };
}

/**
 * Resolve a Morale Test (1d6 + moraleMod >= effectiveQuality):
 *   - Already Shaken/Suppressed units automatically fail and become 'routed'.
 *   - Natural 1 always fails; Natural 6 always passes.
 *   - Steadfast (+1, or +2 with Steadfast Boost), Dauntless (+1), Morale Debuff (-1).
 *   - Fearless: on failure, if `fearlessRoll >= 4`, counts as passed.
 *   - Iron Will (No Retreat): on failure, counts as passed and takes 1 wound per 1-3 in `ironWillRolls`.
 */
export function resolveMoraleTest(input: MoraleTestInput): MoraleTestOutcome {
  const rules = input.specialRules ?? [];
  const effectiveQuality =
    input.heroQuality !== undefined
      ? Math.min(input.quality, input.heroQuality)
      : input.quality;

  if (input.alreadyShaken) {
    return {
      roll: input.roll,
      modifier: 0,
      effectiveQuality,
      passed: false,
      outcome: 'routed',
    };
  }

  let modifier = 0;
  if (hasTrait(rules, 'steadfast')) {
    modifier += hasTrait(rules, 'steadfast-boost') ? 2 : 1;
  }
  if (hasTrait(rules, 'dauntless')) {
    modifier += 1;
  }
  if (hasTrait(rules, 'morale-debuff')) {
    modifier -= 1;
  }

  let passed: boolean;
  if (input.roll <= 1) {
    passed = false;
  } else if (input.roll >= 6) {
    passed = true;
  } else {
    passed = input.roll + modifier >= effectiveQuality;
  }

  if (!passed && hasTrait(rules, 'fearless') && input.fearlessRoll !== undefined) {
    if (input.fearlessRoll >= 4) {
      return {
        roll: input.roll,
        modifier,
        effectiveQuality,
        passed: true,
        fearlessSaved: true,
        outcome: 'passed',
      };
    }
  }

  if (!passed && hasTrait(rules, 'iron-will')) {
    const selfRolls = input.ironWillRolls ?? [];
    const selfWounds = selfRolls.filter((r) => r >= 1 && r <= 3).length;
    return {
      roll: input.roll,
      modifier,
      effectiveQuality,
      passed: true,
      ironWillUsed: true,
      ironWillWounds: selfWounds,
      outcome: 'passed',
    };
  }

  return {
    roll: input.roll,
    modifier,
    effectiveQuality,
    passed,
    outcome: passed ? 'passed' : 'shaken',
  };
}

/** Extract attack roll values for a specific allocation index from server-rolled results. */
export function extractAllocationRolls(results: DiceResult[], index: number = 0): AttackRolls {
  const prefix = `alloc_${index}_`;
  let toHit = results.find((r) => r.purpose === `${prefix}to-hit`);
  let defense = results.find((r) => r.purpose === `${prefix}defense`);
  let regeneration = results.find((r) => r.purpose === `${prefix}regeneration`);
  let trauma = results.find((r) => r.purpose === `${prefix}trauma`);

  // Fallback to unprefixed purposes for single-attack resolutions (legacy / melee / index 0)
  if (!toHit && index === 0) {
    toHit = results.find((r) => r.purpose === 'to-hit');
    defense = results.find((r) => r.purpose === 'defense');
    regeneration = results.find((r) => r.purpose === 'regeneration');
    trauma = results.find((r) => r.purpose === 'trauma');
  }

  if (!toHit || !defense) {
    throw new Error(`Dice results must include 'to-hit' and 'defense' purposes for allocation ${index}`);
  }

  return {
    toHit: toHit.rolls,
    defense: defense.rolls,
    ...(regeneration ? { regeneration: regeneration.rolls } : {}),
    ...(trauma ? { trauma: trauma.rolls } : {}),
  };
}

/** Extract the to-hit, defense, regeneration, and trauma roll values from server-rolled results. */
export function extractAttackRolls(results: DiceResult[]): AttackRolls {
  return extractAllocationRolls(results, 0);
}

/** Extract defender retaliation roll values from server-rolled results (if present). */
export function extractRetaliationRolls(results: DiceResult[]): AttackRolls | null {
  const toHit = results.find((r) => r.purpose === 'retaliation-to-hit');
  const defense = results.find((r) => r.purpose === 'retaliation-defense');
  if (!toHit || !defense) return null;
  const regeneration = results.find((r) => r.purpose === 'retaliation-regeneration');
  const trauma = results.find((r) => r.purpose === 'retaliation-trauma');
  return {
    toHit: toHit.rolls,
    defense: defense.rolls,
    ...(regeneration ? { regeneration: regeneration.rolls } : {}),
    ...(trauma ? { trauma: trauma.rolls } : {}),
  };
}
