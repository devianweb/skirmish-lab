import { DiceSpec, DiceResult } from '../types';
import { getTraitValue, hasTrait, sumTraitValue } from '../rules/traits';

/**
 * Quality/Defense d6 combat and morale resolution (first principles).
 *
 * Core Axioms:
 *   - Natural 1 always fails; Natural 6 always succeeds.
 *   - To-Hit:  roll + hitMod >= baseQuality -> hit
 *   - Defense: roll + coverBonus + shieldBonus - ap >= defense -> hit blocked
 *   - Morale:  1d6 + moraleMod >= effectiveQuality
 *
 * Dice are always rolled by the signaling server (never client-side).
 */

export interface AttackRolls {
  toHit: number[];
  defense: number[];
  regeneration?: number[];
}

export interface MoraleTestInput {
  quality: number;
  /** The d6 rolled; omit for a unit that is already Shaken (it fails without rolling). */
  roll?: number;
  specialRules?: string[];
  alreadyShaken?: boolean;
  /** Quality of a friendly Hero within 6" whose Quality may be used instead. */
  heroQuality?: number;
  /** Optional 1d6 roll for Fearless (Fearless 4+ pass on failure). */
  fearlessRoll?: number;
  /** Optional dice rolls for Iron Will (No Retreat self-wounds on 1-3). */
  ironWillRolls?: number[];
}

export interface MoraleTestOutcome {
  roll: number;
  modifier: number;
  effectiveQuality: number;
  passed: boolean;
  fearlessSaved?: boolean;
  ironWillUsed?: boolean;
  ironWillWounds?: number;
  outcome: 'passed' | 'shaken' | 'routed';
}

export interface CombatOutcome {
  attackCount: number;
  toHitRolls: number[];
  /** hitRolls[i] is true when toHitRolls[i] scored a hit. */
  hitRolls: boolean[];
  /** Bonus hits generated by natural 6s (relentless, furious, surge). */
  bonusHits: number;
  /** Total hits after bonus hits and blast(X) multiplication. */
  hitCount: number;
  defenseRolls: number[];
  /** Re-rolled defense dice when defender rolled a natural 6 against a bane (Bane) attack. */
  rerolledDefenseRolls: number[];
  /** blockedRolls[i] is true when the i-th hit was blocked. */
  blockedRolls: boolean[];
  blockedCount: number;
  /** Wounds prevented by Regeneration (Regeneration 5+). */
  regenerationRolls: number[];
  regenerationSavedCount: number;
  /** Total wounds (Shred's extra wounds included). */
  wounds: number;
  /** Of `wounds`, the extra ones Shred added (plain wounds, never multiplied by Deadly). */
  shredWounds?: number;
  effectiveQuality: number;
  effectiveDefense: number;
  coverApplied: boolean;
  apApplied: number;
  baseQuality: number;
  hitModifiers: string[];
  baseDefense: number;
  defenseModifiers: string[];
}

export interface CombatStats {
  quality: number;
  /** Unit special rules (marksman, furious, surge, rupture, etc.). */
  specialRules?: string[];
  /** Weapon special rules (ap(X), blast(X), deadly(X), rending, reliable, etc.). */
  weaponRules?: string[];
  /** True when this attack is a melee strike. */
  isMelee?: boolean;
  /** True when the attacker charged this activation. */
  isCharging?: boolean;
  /** True when the attacker has already moved this activation. */
  hasMoved?: boolean;
  /** True when the attacker is fatigued or shaken in melee — only hits on natural 6. */
  isFatigued?: boolean;
  /** Distance to target in board units (inches). */
  distance?: number;
}

export interface DefenseStats {
  defense: number;
  inCover?: boolean;
  /** Defender special rules (stealth, riot-shield, regeneration, entrenched, etc.). */
  specialRules?: string[];
  /** Number of alive models in the defending unit (caps blast(X), default 1). */
  modelCount?: number;
  /** Whether the defending unit has moved this round (used by entrenched). */
  hasMoved?: boolean;
}

export interface AttackDiceOptions {
  attackerRules?: string[];
  weaponRules?: string[];
  defenderRules?: string[];
  defenderModelCount?: number;
  isMelee?: boolean;
  isCharging?: boolean;
  isFatigued?: boolean;
  distance?: number;
}

/**
 * Dice specs for one attack. When called without `options`, returns `count`
 * to-hit dice and `count` defense dice. When `options` are provided, scales
 * defense dice for blast/bonus-hit/bane worst-case and appends regeneration
 * dice when applicable.
 */
export function getAttackDiceSpecs(
  attackCount: number,
  options?: AttackDiceOptions
): DiceSpec[] {
  if (!options) {
    return [
      { count: attackCount, sides: 6, purpose: 'to-hit' },
      { count: attackCount, sides: 6, purpose: 'defense' },
    ];
  }

  const allAttackerRules = [
    ...(options.attackerRules ?? []),
    ...(options.weaponRules ?? []),
  ];
  const defenderRules = options.defenderRules ?? [];
  const isMelee = !!options.isMelee;
  const isCharging = !!options.isCharging;
  const distance = options.distance ?? (isMelee ? 1 : 12);

  const bonusPerSix =
    (hasTrait(allAttackerRules, 'surge') ? 1 : 0) +
    (!isMelee && distance > 9 && hasTrait(allAttackerRules, 'relentless') ? 1 : 0) +
    (isMelee && isCharging && hasTrait(allAttackerRules, 'furious') ? 1 : 0);

  const blastVal = getTraitValue(allAttackerRules, 'blast');
  const modelCap = Math.max(1, options.defenderModelCount ?? 1);

  const maxHits = attackCount * (1 + bonusPerSix) * (blastVal ?? 1);
  // A unit takes at most one Blast hit per living model, so that caps what its defense batch can need.
  const unitMaxHits = blastVal !== undefined ? Math.min(maxHits, modelCap) : maxHits;
  const baneMultiplier = hasTrait(allAttackerRules, 'bane') ? 2 : 1;
  const defenseDiceCount =
    blastVal !== undefined
      ? Math.max(1, unitMaxHits * baneMultiplier)
      : Math.max(attackCount, maxHits * baneMultiplier);

  const specs: DiceSpec[] = [
    { count: attackCount, sides: 6, purpose: 'to-hit' },
    { count: defenseDiceCount, sides: 6, purpose: 'defense' },
  ];

  const ignoresRegeneration =
    hasTrait(allAttackerRules, 'bane') ||
    hasTrait(allAttackerRules, 'unstoppable') ||
    hasTrait(allAttackerRules, 'rending');

  if (hasTrait(defenderRules, 'regeneration') && !ignoresRegeneration) {
    const deadlyMult = getTraitValue(allAttackerRules, 'deadly') ?? 1;
    const shredExtra = hasTrait(allAttackerRules, 'shred') ? 1 : 0;
    specs.push({ count: unitMaxHits * (deadlyMult + shredExtra), sides: 6, purpose: 'regeneration' });
  }

  return specs;
}

export interface CombatModifierBreakdown {
  baseQuality: number;
  hitModifiers: string[];
  effectiveQuality: number;
  baseDefense: number;
  defenseModifiers: string[];
  effectiveDefense: number;
  baseAp: number;
  coverApplied: boolean;
}

/**
 * Compute the explicit breakdown of Quality, Hit Modifiers, Defense, and Defense Modifiers.
 */
export function computeCombatModifiers(
  attacker: CombatStats,
  defender: DefenseStats,
  weaponRules: string[] = []
): CombatModifierBreakdown {
  const allAttackerRules = [
    ...(attacker.specialRules ?? []),
    ...(attacker.weaponRules ?? weaponRules),
  ];
  const defenderRules = defender.specialRules ?? [];
  const isMelee = !!attacker.isMelee;
  const isCharging = !!attacker.isCharging;
  const distance = attacker.distance ?? (isMelee ? 1 : 12);

  const baseQuality = hasTrait(allAttackerRules, 'reliable') ? 2 : attacker.quality;
  let hitMod = 0;
  const hitModifiers: string[] = [];

  if (hasTrait(allAttackerRules, 'reliable')) {
    hitModifiers.push('Reliable (Q2)');
  }
  if (!isMelee) {
    if (hasTrait(allAttackerRules, 'marksman')) {
      hitMod += 1;
      hitModifiers.push('+1 Marksman');
    }
    if (hasTrait(defenderRules, 'stealth') && distance > 9) {
      hitMod -= 1;
      hitModifiers.push('-1 Stealth (>9")');
    }
    if (hasTrait(defenderRules, 'entrenched') && !defender.hasMoved && distance > 9) {
      hitMod -= 1;
      hitModifiers.push('-1 Entrenched (>9")');
    }
  } else {
    if (hasTrait(allAttackerRules, 'thrust') && isCharging) {
      hitMod += 1;
      hitModifiers.push('+1 Thrust (charge)');
    }
  }

  if (hasTrait(allAttackerRules, 'unstoppable') && hitMod < 0) {
    hitModifiers.push('Unstoppable (negates penalty)');
    hitMod = 0;
  }

  const isFatiguedMelee = isMelee && !!attacker.isFatigued;
  if (isFatiguedMelee) {
    hitModifiers.push('Fatigued (need 6)');
  }
  const effectiveQuality = isFatiguedMelee
    ? 6
    : Math.max(2, Math.min(6, baseQuality - hitMod));

  const baseAp =
    sumTraitValue(allAttackerRules, 'ap') +
    (isMelee && isCharging && hasTrait(allAttackerRules, 'thrust') ? 1 : 0);

  const blastVal = getTraitValue(allAttackerRules, 'blast');
  const hasBlast = blastVal !== undefined;
  const coverApplied = !isMelee && !!defender.inCover && !hasBlast;
  const coverBonus = coverApplied ? 1 : 0;
  const defenseModifiers: string[] = [];
  if (coverApplied) {
    defenseModifiers.push('+1 Cover');
  }
  const shieldBonus = hasTrait(defenderRules, 'riot-shield') ? 1 : 0;
  if (shieldBonus > 0) {
    defenseModifiers.push('+1 Riot Shield');
  }
  if (baseAp > 0) {
    defenseModifiers.push(`-${baseAp} AP(${baseAp})`);
  }

  const effectiveDefense = Math.max(
    2,
    Math.min(6, defender.defense - coverBonus - shieldBonus + baseAp)
  );

  return {
    baseQuality,
    hitModifiers,
    effectiveQuality,
    baseDefense: defender.defense,
    defenseModifiers,
    effectiveDefense,
    baseAp,
    coverApplied,
  };
}

/**
 * One unit's share of a Blast shot. `offset`/`count` pick which of the shot's hits (in roll order, after
 * every other special rule) this unit takes; `aimedAt` is the unit the shot was aimed at, whose rules decide
 * the to-hit modifiers for the whole shot.
 */
export interface BlastShare {
  offset: number;
  count: number;
  aimedAt?: DefenseStats;
}

/**
 * How many hits a shot produces before a Blast is split between units: every hit (bonus hits included)
 * becomes X hits. For a weapon without Blast this is the plain hit count.
 */
export function countShotHits(
  attacker: CombatStats,
  defender: DefenseStats,
  attackCount: number,
  toHit: number[]
): number {
  const allAttackerRules = [...(attacker.specialRules ?? []), ...(attacker.weaponRules ?? [])];
  const isMelee = !!attacker.isMelee;
  const distance = attacker.distance ?? (isMelee ? 1 : 12);
  const { baseQuality, effectiveQuality } = computeCombatModifiers(attacker, defender);
  const hitMod = baseQuality - effectiveQuality;
  const fatigued = isMelee && !!attacker.isFatigued;
  const bonusPerSix =
    (hasTrait(allAttackerRules, 'surge') ? 1 : 0) +
    (!isMelee && distance > 9 && hasTrait(allAttackerRules, 'relentless') ? 1 : 0) +
    (isMelee && !!attacker.isCharging && hasTrait(allAttackerRules, 'furious') ? 1 : 0);
  const multiplier = getTraitValue(allAttackerRules, 'blast') ?? 1;
  let hits = 0;
  for (const roll of toHit.slice(0, attackCount)) {
    const hit = roll <= 1 ? false : roll >= 6 ? true : fatigued ? false : roll + hitMod >= baseQuality;
    if (hit) hits += (1 + (roll >= 6 ? bonusPerSix : 0)) * multiplier;
  }
  return hits;
}

export interface BlastCandidate {
  unitId: string;
  /** Living models: the most hits this unit can take. */
  cap: number;
}

/**
 * Auto split of a Blast shot's hits. `candidates` are in priority order: the target first, then the other
 * eligible units from nearest to farthest. Hits are dealt as evenly as possible, the odd hits going to the
 * earliest units; a unit never takes more than its cap and the hits it cannot take are re-spread over the
 * units still below theirs. Hits above every cap are lost. Returns each candidate's share, same order.
 */
export function autoSplitBlastHits(totalHits: number, candidates: BlastCandidate[]): number[] {
  const shares = candidates.map(() => 0);
  let remaining = Math.max(0, Math.floor(totalHits));
  while (remaining > 0) {
    const open = candidates.map((_, i) => i).filter((i) => shares[i] < candidates[i].cap);
    if (open.length === 0) break;
    const base = Math.floor(remaining / open.length);
    const extra = remaining % open.length;
    let dealt = 0;
    open.forEach((i, rank) => {
      const give = Math.min(candidates[i].cap - shares[i], base + (rank < extra ? 1 : 0));
      shares[i] += give;
      dealt += give;
    });
    if (dealt === 0) break;
    remaining -= dealt;
  }
  return shares;
}

/** Dice specs for the Impact hits of a charge: X dice, then up to X Defense dice (and Regeneration dice). */
export function getImpactDiceSpecs(impactDice: number, defenderRules: string[] = []): DiceSpec[] {
  if (impactDice <= 0) return [];
  const specs: DiceSpec[] = [
    { count: impactDice, sides: 6, purpose: 'impact' },
    { count: impactDice, sides: 6, purpose: 'impact-defense' },
  ];
  if (hasTrait(defenderRules, 'regeneration')) {
    specs.push({ count: impactDice, sides: 6, purpose: 'impact-regeneration' });
  }
  return specs;
}

export interface ImpactOutcome {
  /** Impact dice rolled. */
  dice: number;
  impactRolls: number[];
  /** Hits scored (each Impact die showing 2+). */
  hitCount: number;
  defenseRolls: number[];
  blockedCount: number;
  regenerationRolls: number[];
  regenerationSavedCount: number;
  wounds: number;
}

/**
 * Impact(X) on a charge: each of the `impactDice` dice showing 2+ is a hit on the target. A hit gets a plain
 * Defense roll (no AP, no cover; Riot Shield still counts) and Regeneration applies to what gets through.
 */
export function resolveImpact(
  impactDice: number,
  defender: DefenseStats,
  rolls: { impact: number[]; defense: number[]; regeneration?: number[] }
): ImpactOutcome {
  const impactRolls = rolls.impact.slice(0, impactDice);
  const hitCount = impactRolls.filter((r) => r >= 2).length;
  if (impactRolls.length < impactDice || rolls.defense.length < hitCount) {
    throw new Error(`Incomplete dice results: need ${impactDice} Impact and ${hitCount} Defense rolls`);
  }
  const shieldBonus = hasTrait(defender.specialRules ?? [], 'riot-shield') ? 1 : 0;
  const hasRegeneration = hasTrait(defender.specialRules ?? [], 'regeneration');
  const defenseRolls = rolls.defense.slice(0, hitCount);
  const regenerationRolls: number[] = [];
  let blockedCount = 0;
  let regenerationSavedCount = 0;
  let wounds = 0;
  for (const roll of defenseRolls) {
    const blocked = roll <= 1 ? false : roll >= 6 ? true : roll + shieldBonus >= defender.defense;
    if (blocked) {
      blockedCount += 1;
      continue;
    }
    if (hasRegeneration && rolls.regeneration && regenerationRolls.length < rolls.regeneration.length) {
      const saveRoll = rolls.regeneration[regenerationRolls.length];
      regenerationRolls.push(saveRoll);
      if (saveRoll >= 5) {
        regenerationSavedCount += 1;
        continue;
      }
    }
    wounds += 1;
  }
  return { dice: impactDice, impactRolls, hitCount, defenseRolls, blockedCount, regenerationRolls, regenerationSavedCount, wounds };
}

/**
 * Resolve one attack deterministically from pre-rolled server dice.
 */
export function resolveAttack(
  attacker: CombatStats,
  defender: DefenseStats,
  attackCount: number,
  rolls: AttackRolls,
  blast?: BlastShare
): CombatOutcome {
  // A Blast share only rolls defense for the hits it takes, which can be fewer than the attack count.
  if (rolls.toHit.length < attackCount || (!blast && rolls.defense.length < attackCount)) {
    throw new Error(
      `Incomplete dice results: need ${attackCount} to-hit and ${attackCount} defense rolls`
    );
  }

  const allAttackerRules = [
    ...(attacker.specialRules ?? []),
    ...(attacker.weaponRules ?? []),
  ];
  const defenderRules = defender.specialRules ?? [];
  const isMelee = !!attacker.isMelee;
  const isCharging = !!attacker.isCharging;
  const distance = attacker.distance ?? (isMelee ? 1 : 12);

  // The shot is aimed at the primary target, so hit modifiers (Stealth etc.) follow it even when this call
  // resolves the share of a Blast that landed on another unit.
  const modifiers = computeCombatModifiers(attacker, defender);
  const { baseQuality, hitModifiers, effectiveQuality } = computeCombatModifiers(attacker, blast?.aimedAt ?? defender);
  const { baseDefense, defenseModifiers, effectiveDefense, baseAp, coverApplied } = modifiers;

  const isFatiguedMelee = isMelee && !!attacker.isFatigued;
  const hitMod = baseQuality - effectiveQuality;

  const toHitRolls = rolls.toHit.slice(0, attackCount);
  const hitRolls = toHitRolls.map((roll) => {
    if (roll <= 1) return false; // Natural 1 always misses
    if (roll >= 6) return true;  // Natural 6 always hits
    if (isFatiguedMelee) return false;
    return roll + hitMod >= baseQuality;
  });

  // 2. Hit Expansion (Bonus hits on 6s, Blast(X), per-hit AP & Regeneration bypass)
  const baseIgnoresRegeneration =
    hasTrait(allAttackerRules, 'bane') ||
    hasTrait(allAttackerRules, 'unstoppable') ||
    hasTrait(allAttackerRules, 'rending');

  const bonusPerSix =
    (hasTrait(allAttackerRules, 'surge') ? 1 : 0) +
    (!isMelee && distance > 9 && hasTrait(allAttackerRules, 'relentless') ? 1 : 0) +
    (isMelee && isCharging && hasTrait(allAttackerRules, 'furious') ? 1 : 0);

  const blastVal = getTraitValue(allAttackerRules, 'blast');
  const modelCap = Math.max(1, defender.modelCount ?? 1);
  const blastMultiplier = blastVal ?? 1;

  let expandedHits: Array<{ ap: number; ignoresRegeneration: boolean }> = [];
  let bonusHits = 0;

  for (let i = 0; i < attackCount; i++) {
    if (!hitRolls[i]) continue;
    const isSix = toHitRolls[i] >= 6;
    let hitAp = baseAp;
    if (isSix && hasTrait(allAttackerRules, 'rending')) {
      hitAp = Math.max(hitAp, 4);
    }
    if (isSix && hasTrait(allAttackerRules, 'rupture')) {
      hitAp += 2;
    }

    const extraFromSix = isSix ? bonusPerSix : 0;
    bonusHits += extraFromSix;
    const copies = (1 + extraFromSix) * blastMultiplier;
    for (let c = 0; c < copies; c++) {
      expandedHits.push({ ap: hitAp, ignoresRegeneration: baseIgnoresRegeneration });
    }
  }

  // Blast: a unit takes at most one hit per living model; with a split, this unit takes its own share.
  if (blastVal !== undefined) {
    expandedHits = blast
      ? expandedHits.slice(blast.offset, blast.offset + Math.min(blast.count, modelCap))
      : expandedHits.slice(0, modelCap);
  }

  const hitCount = expandedHits.length;

  // 3. Defense Rolls (Cover +1, Riot Shield +1, AP -AP, Bane re-rolls 6s)
  const isBane = hasTrait(allAttackerRules, 'bane');
  const coverBonus = coverApplied ? 1 : 0;
  const shieldBonus = hasTrait(defender.specialRules ?? [], 'riot-shield') ? 1 : 0;

  const usedDefenseRolls: number[] = [];
  const rerolledDefenseRolls: number[] = [];
  const blockedRolls: boolean[] = [];
  const unblockedHits: Array<{ ap: number; ignoresRegeneration: boolean; defenseRoll: number }> = [];

  let defCursor = 0;
  for (const hit of expandedHits) {
    const rawRoll =
      defCursor < rolls.defense.length
        ? rolls.defense[defCursor++]
        : rolls.defense[rolls.defense.length - 1];

    let finalDefRoll = rawRoll;
    if (rawRoll >= 6 && isBane && defCursor < rolls.defense.length) {
      rerolledDefenseRolls.push(rawRoll);
      finalDefRoll = rolls.defense[defCursor++];
    }
    usedDefenseRolls.push(finalDefRoll);

    let blocked: boolean;
    if (finalDefRoll <= 1) {
      blocked = false; // Natural 1 always fails
    } else if (finalDefRoll >= 6) {
      blocked = true;  // Natural 6 always blocks
    } else {
      blocked = finalDefRoll + coverBonus + shieldBonus - hit.ap >= defender.defense;
    }

    blockedRolls.push(blocked);
    if (!blocked) {
      unblockedHits.push({ ...hit, defenseRoll: finalDefRoll });
    }
  }

  const blockedCount = blockedRolls.filter(Boolean).length;

  // 4. Wound Multipliers (Deadly(X)) & Regeneration (Regeneration 5+)
  const deadlyMult = getTraitValue(allAttackerRules, 'deadly') ?? 1;
  const hasRegeneration = hasTrait(defenderRules, 'regeneration');
  const regenerationRolls: number[] = [];
  let regenerationSavedCount = 0;
  let regenerationCursor = 0;
  let wounds = 0;

  // Shred: an unmodified Defense roll of 1 against the weapon adds one extra (plain) wound
  const hasShred = hasTrait(allAttackerRules, 'shred');
  let shredWounds = 0;

  for (const hit of unblockedHits) {
    const woundCount = deadlyMult + (hasShred && hit.defenseRoll === 1 ? 1 : 0);
    for (let w = 0; w < woundCount; w++) {
      if (hasRegeneration && !hit.ignoresRegeneration && rolls.regeneration && regenerationCursor < rolls.regeneration.length) {
        const wRoll = rolls.regeneration[regenerationCursor++];
        regenerationRolls.push(wRoll);
        if (wRoll >= 5) {
          regenerationSavedCount += 1;
          continue;
        }
      }
      wounds += 1;
      if (w >= deadlyMult) shredWounds += 1;
    }
  }

  return {
    attackCount,
    toHitRolls,
    hitRolls,
    bonusHits,
    hitCount,
    defenseRolls: usedDefenseRolls,
    rerolledDefenseRolls,
    blockedRolls,
    blockedCount,
    regenerationRolls,
    regenerationSavedCount,
    wounds,
    ...(shredWounds > 0 ? { shredWounds } : {}),
    effectiveQuality,
    effectiveDefense,
    coverApplied,
    apApplied: baseAp,
    baseQuality,
    hitModifiers,
    baseDefense,
    defenseModifiers,
  };
}

/**
 * Resolve a Morale Test: a Quality test (1d6 + moraleMod >= effectiveQuality).
 *   - A Shaken unit always fails (no roll needed).
 *   - Natural 1 always fails; natural 6 always passes.
 *   - Steadfast (+1, or +2 with Steadfast Boost), Dauntless (+1), Morale Debuff (-1) modify the roll
 *     (faction traits, until 14C-3 retires them).
 *   - Fearless: after a failure (including the automatic one while Shaken), `fearlessRoll >= 4` counts as passed.
 *   - Iron Will (No Retreat): on failure, counts as passed and takes 1 wound per 1-3 in `ironWillRolls`.
 * A plain failure is 'shaken'. Only a failed melee test can Rout; the caller turns that into 'routed'.
 */
export function resolveMoraleTest(input: MoraleTestInput): MoraleTestOutcome {
  const rules = input.specialRules ?? [];
  const effectiveQuality =
    input.heroQuality !== undefined
      ? Math.min(input.quality, input.heroQuality)
      : input.quality;
  const roll = input.roll ?? 0;

  let modifier = 0;
  if (hasTrait(rules, 'steadfast')) {
    modifier += hasTrait(rules, 'steadfast-boost') ? 2 : 1;
  }
  if (hasTrait(rules, 'dauntless')) {
    modifier += 1;
  }
  if (hasTrait(rules, 'morale-debuff')) {
    modifier -= 1;
  }

  let passed: boolean;
  if (input.alreadyShaken) {
    passed = false;
  } else if (roll <= 1) {
    passed = false;
  } else if (roll >= 6) {
    passed = true;
  } else {
    passed = roll + modifier >= effectiveQuality;
  }

  if (!passed && hasTrait(rules, 'fearless') && input.fearlessRoll !== undefined) {
    if (input.fearlessRoll >= 4) {
      return {
        roll,
        modifier,
        effectiveQuality,
        passed: true,
        fearlessSaved: true,
        outcome: 'passed',
      };
    }
  }

  if (!passed && !input.alreadyShaken && hasTrait(rules, 'iron-will')) {
    const selfRolls = input.ironWillRolls ?? [];
    const selfWounds = selfRolls.filter((r) => r >= 1 && r <= 3).length;
    return {
      roll,
      modifier,
      effectiveQuality,
      passed: true,
      ironWillUsed: true,
      ironWillWounds: selfWounds,
      outcome: 'passed',
    };
  }

  return {
    roll,
    modifier,
    effectiveQuality,
    passed,
    outcome: passed ? 'passed' : 'shaken',
  };
}

/** Extract attack roll values for a specific allocation index from server-rolled results. */
export function extractAllocationRolls(results: DiceResult[], index: number = 0): AttackRolls {
  const prefix = `alloc_${index}_`;
  let toHit = results.find((r) => r.purpose === `${prefix}to-hit`);
  let defense = results.find((r) => r.purpose === `${prefix}defense`);
  let regeneration = results.find((r) => r.purpose === `${prefix}regeneration`);

  // Fallback to unprefixed purposes for single-attack resolutions (legacy / melee / index 0)
  if (!toHit && index === 0) {
    toHit = results.find((r) => r.purpose === 'to-hit');
    defense = results.find((r) => r.purpose === 'defense');
    regeneration = results.find((r) => r.purpose === 'regeneration');
  }

  if (!toHit || !defense) {
    throw new Error(`Dice results must include 'to-hit' and 'defense' purposes for allocation ${index}`);
  }

  return {
    toHit: toHit.rolls,
    defense: defense.rolls,
    ...(regeneration ? { regeneration: regeneration.rolls } : {}),
  };
}

/** Dice purpose of one defending unit's Blast batch (`alloc_<i>_` is added when the shot has several weapons). */
export function blastPurpose(unitId: string, kind: 'defense' | 'regeneration', allocationIndex?: number): string {
  return `${allocationIndex === undefined ? '' : `alloc_${allocationIndex}_`}blast_${unitId}_${kind}`;
}

/** Extract the defense (and regeneration) rolls of a Blast share that landed on another unit. */
export function extractBlastRolls(
  results: DiceResult[],
  unitId: string,
  toHit: number[],
  allocationIndex?: number
): AttackRolls {
  const defense = results.find((r) => r.purpose === blastPurpose(unitId, 'defense', allocationIndex));
  const regeneration = results.find((r) => r.purpose === blastPurpose(unitId, 'regeneration', allocationIndex));
  if (!defense) throw new Error(`Dice results must include a Blast defense batch for ${unitId}`);
  return { toHit, defense: defense.rolls, ...(regeneration ? { regeneration: regeneration.rolls } : {}) };
}

/** Extract the to-hit, defense, and regeneration roll values from server-rolled results. */
export function extractAttackRolls(results: DiceResult[]): AttackRolls {
  return extractAllocationRolls(results, 0);
}

/** Extract defender retaliation roll values from server-rolled results (if present). */
export function extractRetaliationRolls(results: DiceResult[]): AttackRolls | null {
  const toHit = results.find((r) => r.purpose === 'retaliation-to-hit');
  const defense = results.find((r) => r.purpose === 'retaliation-defense');
  if (!toHit || !defense) return null;
  const regeneration = results.find((r) => r.purpose === 'retaliation-regeneration');
  return {
    toHit: toHit.rolls,
    defense: defense.rolls,
    ...(regeneration ? { regeneration: regeneration.rolls } : {}),
  };
}
